async function writeManagedRules(registry) {
  const blocks = registry.decisions
    .filter((item) => item.status === 'active' && item.ruleFile === '.codex/rules/project-decisions.rules')
    .sort((a, b) => a.decisionId.localeCompare(b.decisionId))
    .map((item) => renderPrefixRule({
      decisionId: item.decisionId,
      pattern: item.rulePattern,
      decision: item.decision,
      justification: item.reason,
      match: item.rulePattern,
      notMatch: item.notMatch ?? [],
    }))
  await writeFile(managedRulePath, `# Generated by scripts/command-approval/command-approval.mjs.\n# Edit through commands:approval:record.\n\n${blocks.join('\n\n')}\n`, 'utf8')
}

async function syncDerived(registry) {
  await writeJson(registryPath, registry)
  await writeManagedRules(registry)
  await writeFile(summaryPath, renderSummary(registry), 'utf8')
}

async function classify(options) {
  const pattern = patternOption(options)
  const output = { authorization: classifyAuthorizationText(options.text ?? '') }
  if (pattern) output.rule = classifyRulePattern(pattern)
  console.log(JSON.stringify(output, null, 2))
}

async function record(options) {
  const scope = options.scope ?? 'project'
  const decision = options.decision
  const pattern = patternOption(options)
  const reason = String(options.reason ?? '').trim()
  if (scope !== 'project') throw new Error('项目工具不写用户全局规则；请明确授权后在用户级单独处理。')
  if (!['allow', 'prompt', 'forbidden'].includes(decision)) throw new Error('decision 必须是 allow、prompt 或 forbidden。')
  if (!reason) throw new Error('必须提供 --reason。')
  const safety = classifyRulePattern(pattern)
  if (decision === 'allow' && (safety.classification !== 'project-specific' || !safety.allowEligible)) {
    throw new Error(`拒绝写入 allow：${safety.classification}；${safety.reason}`)
  }
  if (safety.reason.includes('敏感字段') || safety.reason.includes('复杂 shell')) throw new Error(`拒绝持久化：${safety.reason}`)

  const now = options.date ?? new Date().toISOString().slice(0, 10)
  const registry = await readJson(registryPath)
  const result = upsertApprovalDecision(registry, {
    scope,
    source: options.source ?? 'user-explicit',
    commandClass: options.class ?? (decision === 'allow' ? 'project-routine' : 'guardrail'),
    ruleFile: '.codex/rules/project-decisions.rules',
    rulePattern: pattern,
    decision,
    reason,
    createdAt: now,
    lastReviewedAt: now,
  })
  await syncDerived(result.registry)
  console.log(JSON.stringify({ action: result.action, decision: result.decision }, null, 2))
}

async function audit(options) {
  if (!options.input) throw new Error('audit 需要 --input 指向待只读检查的用户规则文件。')
  const inputPath = path.resolve(options.input)
  const snapshotPath = path.resolve(options.snapshot ?? defaultSnapshotPath)
  const current = createRuleSnapshot(parsePrefixRules(await readFile(inputPath, 'utf8')))
  const hasPrevious = existsSync(snapshotPath)
  const previous = hasPrevious ? await readJson(snapshotPath) : { schemaVersion: 1, rules: [] }
  const previousHandled = new Map((previous.rules ?? []).map((rule) => [rule.fingerprint, rule.handled]))
  for (const rule of current.rules) rule.handled = previousHandled.get(rule.fingerprint) ?? false
  const diff = hasPrevious || options['report-existing'] === 'true'
    ? compareRuleSnapshots(previous, current)
    : { added: [], removed: [] }
  await writeJson(snapshotPath, current)
  console.log(JSON.stringify({ baselineCreated: !hasPrevious, parsedRules: current.rules.length, ...diff }, null, 2))
}

async function retire(options) {
  const scope = options.scope ?? 'project'
  if (scope !== 'project') throw new Error('项目工具不退休用户全局规则。')
  const pattern = patternOption(options)
  const reason = String(options.reason ?? '').trim()
  if (!reason) throw new Error('必须提供 --reason。')
  const date = options.date ?? new Date().toISOString().slice(0, 10)
  const result = retireApprovalDecision(await readJson(registryPath), { scope, rulePattern: pattern, reason, date })
  if (result.decision.ruleFile !== '.codex/rules/project-decisions.rules') {
    throw new Error('基线规则不能由 retire 自动移除；请按整体治理流程修改对应规则文件。')
  }
  await syncDerived(result.registry)
  console.log(JSON.stringify({ action: result.action, decision: result.decision }, null, 2))
}

async function validate() {
  const registry = await readJson(registryPath)
  const errors = []
  const ids = new Set()
  for (const item of registry.decisions ?? []) {
    if (ids.has(item.decisionId)) errors.push(`duplicate decisionId: ${item.decisionId}`)
    ids.add(item.decisionId)
    try { classifyRulePattern(item.rulePattern) } catch (error) { errors.push(`${item.decisionId}: ${error.message}`) }
    if (!['allow', 'prompt', 'forbidden'].includes(item.decision)) errors.push(`${item.decisionId}: invalid decision`)
    if (!['active', 'review-required', 'superseded', 'retired', 'rejected'].includes(item.status)) errors.push(`${item.decisionId}: invalid status`)
  }
  const files = (await readdir(rulesDir)).filter((name) => name.endsWith('.rules')).sort()
  for (const name of files) {
    const parsed = parsePrefixRules(await readFile(path.join(rulesDir, name), 'utf8'))
    if (parsed.length === 0 && name !== 'project-decisions.rules') errors.push(`${name}: no literal prefix_rule parsed`)
  }
  if (renderSummary(registry) !== await readFile(summaryPath, 'utf8')) errors.push('命令批准分级表与注册表不一致')

  const codex = codexExecutable()
  const ruleArgs = files.flatMap((name) => ['--rules', path.join(rulesDir, name)])
  const policyCases = [
    { command: ['npm', 'run', 'docs:check-encoding'], expected: 'allow' },
    { command: ['git', 'push', 'origin', 'main'], expected: 'allow' },
    { command: ['git', 'push', '--force', 'origin', 'main'], expected: 'forbidden' },
    { command: ['npm', 'install', 'lodash'], expected: 'prompt' },
    { command: ['npm', 'run', 'external-skills:fetch'], expected: 'prompt' },
    { command: ['npm', 'run', 'project:routine'], expected: 'allow' },
    { command: ['npm', 'run', 'project:skill:init'], expected: 'allow' },
    { command: ['npm', 'run', 'project:gate:changed'], expected: 'allow' },
    { command: ['npm', 'run', 'project:gate:prepush'], expected: 'allow' },
    { command: ['npm', 'run', 'project:gate:ci'], expected: 'allow' },
    { command: ['npm', 'run', 'project:gate:explain'], expected: 'allow' },
    { command: ['npm', 'run', 'project:hooks:test'], expected: 'allow' },
    { command: ['npm', 'run', 'project:hooks:install'], expected: 'prompt' },
  ]
  for (const policyCase of policyCases) {
    const result = spawnSync(codex, ['execpolicy', 'check', ...ruleArgs, '--', ...policyCase.command], { encoding: 'utf8' })
    if (result.status !== 0) {
      errors.push(`codex execpolicy check failed for ${policyCase.command.join(' ')}: ${(result.stderr || result.error?.message || '').trim()}`)
      continue
    }
    try {
      const actual = JSON.parse(result.stdout).decision
      if (actual !== policyCase.expected) errors.push(`${policyCase.command.join(' ')}: expected ${policyCase.expected}, got ${actual}`)
    } catch {
      errors.push(`${policyCase.command.join(' ')}: invalid execpolicy JSON output`)
    }
  }
  if (errors.length) throw new Error(errors.join('\n'))
  console.log(`Command approval governance is valid: ${registry.decisions.length} decisions, ${files.length} rule files.`)
}

async function main() {
  const [command = 'help', ...rest] = process.argv.slice(2)
  const options = argsMap(rest)
  if (command === 'classify') return classify(options)
  if (command === 'record') return record(options)
  if (command === 'audit') return audit(options)
  if (command === 'retire') return retire(options)
  if (command === 'list') return console.log(renderSummary(await readJson(registryPath)))
  if (command === 'render') return syncDerived(await readJson(registryPath))
  if (command === 'validate') return validate()
  console.log('Commands: classify, record, retire, audit, list, render, validate')
}

main().catch((error) => {
  console.error(error.message)
  process.exitCode = 1
})
