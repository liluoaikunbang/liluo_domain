import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import { ROOT, toPosix } from './paths.mjs'
import { loadAllDefinitions } from './registry.mjs'
import { generateMermaid } from './generate-docs.mjs'

async function listJsonFiles(directory) {
  try {
    const entries = await readdir(directory, { withFileTypes: true })
    return entries.filter((entry) => entry.isFile() && entry.name.endsWith('.json')).map((entry) => path.join(directory, entry.name))
  } catch {
    return []
  }
}

function summarizeDefinition(definition) {
  const resources = []
  for (const node of definition.nodes) {
    for (const resource of node.resources ?? []) {
      if (resource.requirement === 'forbidden') continue
      resources.push({
        nodeId: node.id,
        requirement: resource.requirement,
        kind: resource.kind,
        ref: resource.ref,
        selfExecutionAllowed: resource.selfExecutionAllowed,
        fatal: Boolean(resource.fatal),
      })
    }
  }
  return {
    id: definition.id,
    version: definition.version,
    title: definition.title,
    purpose: definition.purpose,
    domain: definition.domain,
    status: definition.status,
    maturity: definition.maturity,
    ownerSkill: definition.ownerSkill,
    tags: definition.tags ?? [],
    entryNodeId: definition.entryNodeId,
    completionGate: definition.completionGate,
    invariants: definition.invariants,
    visualization: definition.visualization,
    nodes: definition.nodes,
    edges: definition.edges,
    resources,
    mermaid: {
      simple: generateMermaid(definition, { view: 'simple' }),
      detail: generateMermaid(definition, { view: 'detail' }),
    },
  }
}

export async function buildViewerData(root = ROOT) {
  const loaded = await loadAllDefinitions(root)
  const workflows = loaded
    .filter(({ definition }) => definition.status === 'active' || definition.status === 'draft')
    .map(({ definition, file }) => ({
      ...summarizeDefinition(definition),
      definitionPath: toPosix(path.relative(root, file)),
    }))
    .sort((left, right) => left.id.localeCompare(right.id))

  const runDirs = [
    path.join(root, 'project-workflows', 'runs', 'examples'),
    path.join(root, 'project-workflows', 'runs'),
  ]
  const runs = []
  for (const dir of runDirs) {
    for (const file of await listJsonFiles(dir)) {
      if (path.basename(path.dirname(file)) === 'briefs') continue
      try {
        const run = JSON.parse(await readFile(file, 'utf8'))
        if (!run.runId || !run.workflowId) continue
        runs.push({
          runId: run.runId,
          workflowId: run.workflowId,
          workflowVersion: run.workflowVersion,
          status: run.status,
          mode: run.mode,
          createdAt: run.createdAt,
          updatedAt: run.updatedAt,
          activeNodeIds: run.activeNodeIds ?? [],
          nodes: run.nodes,
          invocations: run.invocations ?? [],
          completionGate: run.completionGate,
          reportPath: run.reportPath ?? null,
          path: toPosix(path.relative(root, file)),
        })
      } catch {
        // skip invalid
      }
    }
  }
  runs.sort((left, right) => String(right.updatedAt || right.createdAt).localeCompare(String(left.updatedAt || left.createdAt)))

  const skillSet = new Map()
  const agentSet = new Map()
  for (const workflow of workflows) {
    for (const resource of workflow.resources) {
      if (resource.kind === 'skill') {
        const entry = skillSet.get(resource.ref) ?? { id: resource.ref, workflowIds: new Set(), nodeIds: [] }
        entry.workflowIds.add(workflow.id)
        entry.nodeIds.push(`${workflow.id}:${resource.nodeId}`)
        skillSet.set(resource.ref, entry)
      }
      if (resource.kind === 'agent') {
        const entry = agentSet.get(resource.ref) ?? { id: resource.ref, workflowIds: new Set(), nodeIds: [] }
        entry.workflowIds.add(workflow.id)
        entry.nodeIds.push(`${workflow.id}:${resource.nodeId}`)
        agentSet.set(resource.ref, entry)
      }
    }
  }

  const payload = {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    workflows,
    runs,
    overview: {
      skills: [...skillSet.values()].map((item) => ({
        id: item.id,
        workflowIds: [...item.workflowIds],
        nodeCount: item.nodeIds.length,
      })),
      agents: [...agentSet.values()].map((item) => ({
        id: item.id,
        workflowIds: [...item.workflowIds],
        nodeCount: item.nodeIds.length,
      })),
    },
  }

  const outDir = path.join(root, 'project-workflows', 'viewer')
  await mkdir(outDir, { recursive: true })
  const dataJs = `/* generated by scripts/project-workflows — do not edit */\nwindow.__WORKFLOW_VIEWER_DATA__ = ${JSON.stringify(payload, null, 2)};\n`
  await writeFile(path.join(outDir, 'data.js'), dataJs, 'utf8')
  await writeFile(path.join(outDir, 'data.json'), `${JSON.stringify(payload, null, 2)}\n`, 'utf8')
  return {
    workflowCount: workflows.length,
    runCount: runs.length,
    dataPath: 'project-workflows/viewer/data.js',
  }
}
